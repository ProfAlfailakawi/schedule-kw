/**
 * الدرجةُ العلمية هي التي تقول إن العضو «مدرب»: درجاتُ النصاب تحمل «مدرب أ/ب» و«مدرب متخصص أ/ب/ج»، فلا خانةَ
 * «مدرب» ثانية في نموذج «أستاذ جديد» (المالك 2026-11-19). الدالّةُ نقيّة ويستعملها النموذجُ والخادمُ معاً.
 */
export const isTraineeRankName = (name: unknown): boolean => /^\s*مدرب(?:\s|$)/.test(String(name ?? ""));
